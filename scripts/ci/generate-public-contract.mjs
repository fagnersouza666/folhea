#!/usr/bin/env node
// Build-time generation only: no HTTP, Maven plugin or runtime dependency.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const catalogFile = 'shared/public-contract.json';
const javaFile = 'backend/src/main/java/com/folhea/shared/ProblemTypes.java';
const tsFile = 'frontend/src/app/core/api/problem-types.generated.ts';
function requireValid(condition) {
  if (!condition) throw new Error('Invalid public contract: canonical HTTPS origin and named relative problem IDs required');
}
function render(raw) {
  requireValid(raw && typeof raw === 'object' && !Array.isArray(raw) &&
    Object.keys(raw).sort().join(',') === 'problemTypes,publicOrigin' && typeof raw.publicOrigin === 'string');
  let origin;
  try { origin = new URL(raw.publicOrigin); } catch { requireValid(false); }
  requireValid(origin.protocol === 'https:' && origin.origin === raw.publicOrigin && !origin.username && !origin.password);
  const types = raw.problemTypes;
  requireValid(types && typeof types === 'object' && !Array.isArray(types) && Object.keys(types).length > 0);
  const entries = Object.entries(types).sort(([left], [right]) => left.localeCompare(right, 'en'));
  const values = new Set();
  for (const [name, value] of entries) {
    requireValid(/^[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)*$/.test(name) && typeof value === 'string' &&
      /^\/problems\/[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(value) &&
      name === value.slice('/problems/'.length).replaceAll('-', '_').toUpperCase() && !values.has(value));
    values.add(value);
  }
  const header = '// Generated by scripts/ci/generate-public-contract.mjs from shared/public-contract.json. Do not edit.\n';
  const java = `${header}package com.folhea.shared;\n\npublic final class ProblemTypes {\n    private ProblemTypes() {}\n\n${entries.map(([name, value]) => `    public static final String ${name} = ${JSON.stringify(value)};`).join('\n')}\n}\n`;
  const ts = `${header}export const PUBLIC_SITE_ORIGIN = ${JSON.stringify(raw.publicOrigin)};\n\nexport const PROBLEM_TYPES = {\n${entries.map(([name, value]) => `  ${name}: ${JSON.stringify(value)},`).join('\n')}\n} as const;\n`;
  return [[javaFile, java], [tsFile, ts]];
}
try {
  const args = process.argv.slice(2);
  if (!(args.length === 0 || (args.length === 1 && args[0] === '--check'))) {
    throw new Error('Usage: node scripts/ci/generate-public-contract.mjs [--check]');
  }
  const outputs = render(JSON.parse(readFileSync(join(root, catalogFile), 'utf8')));
  if (args[0] === '--check') {
    const stale = outputs.filter(([name, text]) => !existsSync(join(root, name)) || readFileSync(join(root, name), 'utf8') !== text);
    if (stale.length) throw new Error('Generated public contract is stale: ' + stale.map(([name]) => name).join(', ') + '. Run the generator.');
    console.log('Public contract: Java/TypeScript outputs match the canonical catalog');
  } else {
    for (const [name, text] of outputs) {
      mkdirSync(dirname(join(root, name)), { recursive: true });
      writeFileSync(join(root, name), text);
    }
    console.log('Public contract: generated Java/TypeScript from the canonical catalog');
  }
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
